const messages: Record<Locale, Record<ClockMessageKey, string>> = { en, fr };

export type ClockT = (key: ClockMessageKey, params?: Record<string, string | number>) => string;

/** The clocks dictionary in the current locale, `{name}` placeholders included. */
export function useClockT(): ClockT {
  const { locale } = useI18n();
  return (key, params) => {
    const template = messages[locale][key];
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match,
    );
  };
}
