const messages: Record<Locale, Record<CategoryMessageKey, string>> = { en, fr };

export type CategoryT = (
  key: CategoryMessageKey,
  params?: Record<string, string | number>,
) => string;

/** The categories dictionary in the current locale, `{name}` placeholders included. */
export function useCategoryT(): CategoryT {
  const { locale } = useI18n();
  return (key, params) => {
    const template = messages[locale][key];
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match,
    );
  };
}
