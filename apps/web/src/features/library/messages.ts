const messages: Record<Locale, Record<LibraryMessageKey, string>> = { en, fr };

export type LibraryT = (key: LibraryMessageKey, params?: Record<string, string | number>) => string;

/** The library dictionary in the current locale, `{name}` placeholders included. */
export function useLibraryT(): LibraryT {
  const { locale } = useI18n();
  return (key, params) => {
    const template = messages[locale][key];
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match,
    );
  };
}
