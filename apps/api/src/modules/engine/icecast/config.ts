import type { StreamMount } from './mounts.ts';

// Icecast 2.5 configuration for every station's mounts (the mount plan, mounts.ts).
//
// The global secrets (master source password, relay and admin credentials) are not rendered:
// they are placeholders that the Icecast container replaces from its own environment each time
// it loads the file (deploy/icecast/entrypoint.sh). Each mount does carry its station's source
// password (passwords.ts): derived from the master, it only opens that station's mounts. The
// file is therefore written readable by Icecast's user only.

export type IcecastConfigOptions = {
  /** Public host name of the streams (`stream.vandale.fr`): used in playlists and YP. */
  hostname: string;
  location?: string;
  adminEmail?: string;
  /** Inside the container. Caddy proxies 443 to it; never published directly in production. */
  port?: number;
  bindAddress?: string;
  /** Connections on top of the mounts' listeners: stats, admin, status page, file requests. */
  extraClients?: number;
  /** Icecast's own `<limits>`. Seconds. */
  sourceTimeout?: number;
  headerTimeout?: number;
  clientTimeout?: number;
  /** Icecast log level: `error`, `warning`, `information` or `debug`. */
  logLevel?: 'error' | 'warning' | 'information' | 'debug';
};

export type IcecastConfigSecrets = {
  /** The source password of a station's mounts (`icecastSourcePassword(master, stationId)`). */
  sourcePasswordFor(stationId: string): string;
};

/** Placeholder the container entrypoint replaces with the matching environment variable. */
export const SECRET_PLACEHOLDER = {
  sourcePassword: 'env:ICECAST_SOURCE_PASSWORD',
  relayPassword: 'env:ICECAST_RELAY_PASSWORD',
  adminUser: 'env:ICECAST_ADMIN_USER',
  adminPassword: 'env:ICECAST_ADMIN_PASSWORD',
} as const;

/** Icecast's hard cap on `<clients>` is not documented; this keeps a typo from exhausting fds. */
const MAX_CLIENTS = 100_000;

export function xmlEscape(value: string): string {
  return value
    .replace(/[<>&'"]/g, (ch) => `&#${ch.charCodeAt(0)};`)
    .replace(
      // Control characters are not allowed in XML 1.0 at all.
      // biome-ignore lint/suspicious/noControlCharactersInRegex: that is the point
      /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g,
      '',
    );
}

const el = (name: string, value: string | number) =>
  `<${name}>${xmlEscape(String(value))}</${name}>`;

function mountBlock(m: StreamMount, secrets: IcecastConfigSecrets): string {
  const lines = [
    el('mount-name', m.mount),
    // Only this station's engine can source it: Icecast then refuses every other password.
    el('password', secrets.sourcePasswordFor(m.stationId)),
    // Liquidsoap sends the stream name and metadata as UTF-8. Without this Icecast reads them
    // as Latin-1 on MP3/AAC mounts (Ogg carries its own) and shows non-ASCII names garbled.
    el('charset', 'UTF-8'),
    el('max-listeners', m.maxListeners),
    el('burst-size', m.burstSize),
    el('queue-size', m.queueSize),
    el('public', m.public ? 1 : 0),
  ];
  if (m.fallbackFile) {
    lines.push(
      el('fallback-mount', m.fallbackFile),
      // Listeners on the fallback go back to the stream as soon as the engine reconnects.
      el('fallback-override', 'all'),
      el('fallback-when-full', 1),
    );
  }
  if (m.introFile) lines.push(el('intro', m.introFile));
  return `    <mount type="normal">\n${lines.map((l) => `        ${l}`).join('\n')}\n    </mount>`;
}

/**
 * Renders `icecast.xml`. Deterministic: same plan and options, same bytes, so the sync only
 * reloads Icecast when something changed.
 */
export function renderIcecastConfig(
  mounts: StreamMount[],
  options: IcecastConfigOptions,
  secrets: IcecastConfigSecrets,
): string {
  const o = {
    location: 'Earth',
    adminEmail: 'icemaster@localhost',
    port: 8000,
    extraClients: 100,
    sourceTimeout: 10,
    headerTimeout: 15,
    clientTimeout: 30,
    logLevel: 'information' as const,
    ...options,
  };
  const listeners = mounts.reduce((sum, m) => sum + m.maxListeners, 0);
  const clients = Math.min(MAX_CLIENTS, listeners + o.extraClients);
  // A fallback file being played counts as a source too.
  const sources = mounts.length + mounts.filter((m) => m.fallbackFile).length + 2;

  return `<?xml version="1.0"?>
<!--
  Generated by apps/api/src/modules/engine/icecast from the stations' settings. Do not edit:
  the api rewrites it and Icecast reloads it (SIGHUP, deploy/icecast/entrypoint.sh).
  Global passwords are filled in by the container from its environment.
-->
<icecast>
    ${el('location', o.location)}
    ${el('admin', o.adminEmail)}
    ${el('hostname', o.hostname)}

    <limits>
        ${el('clients', clients)}
        ${el('sources', sources)}
        ${el('queue-size', 524288)}
        ${el('burst-size', 65536)}
        ${el('client-timeout', o.clientTimeout)}
        ${el('header-timeout', o.headerTimeout)}
        ${el('source-timeout', o.sourceTimeout)}
    </limits>

    <authentication>
        ${el('source-password', SECRET_PLACEHOLDER.sourcePassword)}
        ${el('relay-password', SECRET_PLACEHOLDER.relayPassword)}
        ${el('admin-user', SECRET_PLACEHOLDER.adminUser)}
        ${el('admin-password', SECRET_PLACEHOLDER.adminPassword)}
    </authentication>

    <listen-socket>
        ${el('port', o.port)}${o.bindAddress ? `\n        ${el('bind-address', o.bindAddress)}` : ''}
    </listen-socket>

    <http-headers>
        <header type="cors" name="Access-Control-Allow-Origin" />
        <header type="cors" name="Access-Control-Allow-Headers" />
        <header type="cors" name="Access-Control-Expose-Headers" />
    </http-headers>

    <!-- Any mount without its own block (none should stream there) still gets UTF-8. -->
    <mount type="default">
        ${el('charset', 'UTF-8')}
    </mount>

${mounts.map((m) => mountBlock(m, secrets)).join('\n\n')}

    <fileserve>1</fileserve>

    <paths>
        <basedir>/usr/share/icecast</basedir>
        <logdir>/var/log/icecast</logdir>
        <webroot>/usr/share/icecast/web</webroot>
        <adminroot>/usr/share/icecast/admin</adminroot>
        <reportxmldb>/usr/share/icecast/report-db.xml</reportxmldb>
        <alias source="/" destination="/status.xsl"/>
    </paths>

    <logging>
        <accesslog>-</accesslog>
        <errorlog>-</errorlog>
        ${el('loglevel', o.logLevel)}
    </logging>

    <security>
        <chroot>false</chroot>
    </security>
</icecast>
`;
}
