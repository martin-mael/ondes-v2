// Autocue against the dev Postgres, Garage and RabbitMQ, on audio generated by ffmpeg (FLAC
// playout copies, 44.1 kHz, 1024-sample blocks, as ingest makes them). Needs ffmpeg on the
// PATH (apps/worker/test/bin runs the worker image's) and the S3_* variables (skipped without
// S3_ENDPOINT, like ingest's tests).

const exec = promisify(execFile);
const enabled = Boolean(process.env.S3_ENDPOINT);
const rabbitUrl = process.env.RABBITMQ_URL ?? 'amqp://ondes:ondes@127.0.0.1:5672/ondes';
const system: Actor = { type: 'system', name: 'test' };
const user: Actor = { type: 'user', userId: '0199f6a0-0000-7000-8000-00000000000a' };
const tools = defaultTools();
const RATE = 44_100;
const at = (seconds: number) => Math.round(seconds * RATE);

let tdb: TestDatabase;
let storage: Storage;
let dir: string;
let deps: AutocueDeps;
const fixtures: Record<string, string> = {};

/** A FLAC playout copy of `seconds` of `aevalsrc` audio (a random pitch: unique hashes). */
async function generate(name: string, seconds: number, envelope: string) {
  const path = join(dir, `${name}.flac`);
  const tone = `sin(2*PI*${200 + Math.floor(Math.random() * 1000)}*t)`;
  await exec(tools.ffmpeg, [
    '-nostdin',
    '-v',
    'error',
    '-y',
    '-f',
    'lavfi',
    '-i',
    `aevalsrc='0.4*${tone}*(${envelope})':s=${RATE}:d=${seconds}`,
    '-ac',
    '2',
    '-c:a',
    'flac',
    '-frame_size',
    '1024',
    '-sample_fmt',
    's16',
    path,
  ]);
  fixtures[name] = path;
}

beforeAll(async () => {
  if (!enabled) return;
  tdb = await createTestDatabase();
  storage = createS3Storage(loadStorageConfig());
  dir = await mkdtemp(join(tmpdir(), 'ondes-autocue-test-'));
  deps = { db: tdb.db, storage, tools };
  // 2 s of silence, 14 s of tone, a 6 s linear fade, 2 s of silence.
  const song = 'if(lt(t,2),0,if(lt(t,16),1,if(lt(t,22),(22-t)/6,0)))';
  await generate('song', 24, song);
  // The same 50 dB lower: thresholds follow the track's own loudness.
  await generate('quiet', 24, `0.00316*${song}`);
  // 8 s of tone, 15 s of silence, a 4 s hidden track.
  await generate('hidden', 27, 'lt(t,8)+between(t,23,27)');
  await generate('silent', 5, '0');
}, 60_000);

afterAll(async () => {
  await tdb?.drop();
  if (dir) await rm(dir, { recursive: true, force: true });
});

let n = 0;
async function tenant(engineSettings?: Record<string, unknown>) {
  n++;
  const org = (await createOrganization(tdb.db, system, { slug: `ac-${n}`, name: 'Org' })).id;
  const st = await createStation(
    tdb.db,
    { actor: system, scope: await resolveOrgScope(tdb.db, org) },
    { slug: `ac-fm-${n}`, name: 'FM', timezone: 'Europe/Paris' },
  );
  const scope = await resolveStationScope(tdb.db, org, st.id);
  if (engineSettings) await setEngineSettings(scope, engineSettings);
  return scope;
}

async function setEngineSettings(scope: StationScope, settings: Record<string, unknown>) {
  await tdb.sql`update station set engine_settings = ${JSON.stringify(settings)}::jsonb where id = ${scope.stationId}`;
}

/** An asset whose master and playout copy are the fixture, stored like ingest stores them. */
async function asset(scope: StationScope, fixture: string) {
  const bytes = await readFile(fixtures[fixture] as string);
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const storageKey = contentKey({ orgId: scope.orgId, sha256, ext: 'flac' });
  await storage.put(storageKey, bytes);
  const { stdout } = await exec(tools.ffprobe, [
    '-v',
    'error',
    '-show_entries',
    'stream=duration_ts',
    '-of',
    'csv=p=0',
    fixtures[fixture] as string,
  ]);
  const durationSamples = Number(stdout.trim());
  const ctx = { actor: system, scope };
  const created = await createAsset(tdb.db, ctx, { type: 'song', title: fixture });
  for (const role of ['master', 'playout'] as const) {
    await putAssetFile(tdb.db, ctx, created.id, {
      role,
      storageKey,
      sha256,
      sizeBytes: bytes.length,
      codec: 'flac',
      mimeType: 'audio/flac',
      sampleRate: RATE,
      channels: 2,
      bitDepth: 16,
      durationSamples,
      ...(role === 'playout' ? { flacBlockSize: 1024 } : {}),
    });
  }
  const payload: AutocueJobPayload = {
    orgId: scope.orgId,
    stationId: scope.stationId,
    assetId: created.id,
    playoutSha256: sha256,
    analyzerVersion: 'autocue/1',
  };
  return { id: created.id, sha256, durationSamples, payload };
}

/** Within `frames` 100 ms frames of `seconds`. */
function near(value: number | null | undefined, seconds: number, frames = 1) {
  expect(value).not.toBeNull();
  expect(Math.abs((value ?? 0) - at(seconds))).toBeLessThanOrEqual(frames * 4410);
}

describe.skipIf(!enabled)('autocue (integration)', () => {
  it('cues a song: silence trimmed, the next track on the fade, a natural fade-out', async () => {
    const scope = await tenant();
    const a = await asset(scope, 'song');
    const cues = await autocue(deps, a.payload);
    expect(cues).toMatchObject({ sampleRate: RATE, analyzerVersion: 'autocue/1' });
    // The tone starts on a frame boundary: sample-exact.
    expect(cues?.cueIn).toMatchObject({ samples: at(2), source: 'auto', locked: false });
    // I ≈ -12.3 LUFS (the tone, a little less for the fade). -42 LU: the fade's last frame.
    near(cues?.cueOut.samples, 22, 2);
    // -8 LU: about 3.9 s into the fade.
    near(cues?.crossStartNext.samples, 19.9, 2);
    const fadeOut = cues?.fadeOut.samples ?? 0;
    expect(fadeOut).toBeGreaterThan(at(1));
    expect((cues?.crossStartNext.samples ?? 0) + fadeOut).toBe(cues?.cueOut.samples);
    expect(cues?.introEnd.samples).toBeNull();
    expect(cues?.fadeIn.samples).toBeNull();
    for (const field of ['cueIn', 'cueOut', 'crossStartNext', 'fadeOut'] as const) {
      expect(Number.isInteger(cues?.[field].samples)).toBe(true);
    }
  });

  it('cues a quiet track by its own loudness', async () => {
    const scope = await tenant();
    const quiet = await autocue(deps, (await asset(scope, 'quiet')).payload);
    expect(quiet?.cueIn.samples).toBe(at(2));
    near(quiet?.cueOut.samples, 22, 2);
    near(quiet?.crossStartNext.samples, 19.9, 2);
  });

  it('ends a track before a hidden track', async () => {
    const scope = await tenant();
    const cues = await autocue(deps, (await asset(scope, 'hidden')).payload);
    expect(cues?.cueIn.samples).toBe(0);
    near(cues?.cueOut.samples, 8);
    // Off for this station: the hidden track plays.
    const all = await tenant({ autocue: { blankSkipSeconds: 0 } });
    const whole = await autocue(deps, (await asset(all, 'hidden')).payload);
    near(whole?.cueOut.samples, 27);
    expect(whole?.analyzerVersion).toMatch(/^autocue\/1\+/);
  });

  it('gives a silent file its whole length', async () => {
    const scope = await tenant();
    const a = await asset(scope, 'silent');
    const cues = await autocue(deps, a.payload);
    expect(cues?.cueIn.samples).toBe(0);
    expect(cues?.cueOut.samples).toBe(a.durationSamples);
    expect(cues?.crossStartNext.samples).toBeNull();
  });

  it('never overwrites points a person set or locked, and fits the others inside', async () => {
    const scope = await tenant();
    const a = await asset(scope, 'song');
    // Before any analysis: a manual cue-out (cut early), a locked empty fade-in, a locked
    // crossfade point.
    await updateCues(tdb.db, { actor: user, scope }, a.id, {
      sampleRate: RATE,
      cueOut: { samples: at(12) },
      fadeIn: { locked: true },
      crossStartNext: { samples: at(10), locked: true },
    });
    const cues = await autocue(deps, a.payload);
    expect(cues?.cueIn).toMatchObject({ samples: at(2), source: 'auto' });
    expect(cues?.cueOut).toMatchObject({ samples: at(12), source: 'manual', locked: false });
    expect(cues?.crossStartNext).toMatchObject({ samples: at(10), source: 'manual', locked: true });
    expect(cues?.fadeIn).toMatchObject({ samples: null, locked: true });
    // Loud up to the person's cue-out: no natural fade there.
    expect(cues?.fadeOut.samples).toBeNull();

    // New thresholds re-analyse; the person's points still stand.
    await setEngineSettings(scope, { autocue: { overlayLu: -4 } });
    const again = await autocue(deps, a.payload);
    expect(again?.analyzerVersion).not.toBe(cues?.analyzerVersion);
    expect(again?.cueOut).toMatchObject({ samples: at(12), source: 'manual' });
    expect(again?.crossStartNext).toMatchObject({ samples: at(10), locked: true });
  });

  it('does nothing for a replaced playout copy, a deleted asset or the same version', async () => {
    const scope = await tenant();
    const a = await asset(scope, 'song');
    expect(await autocue(deps, { ...a.payload, playoutSha256: 'f'.repeat(64) })).toBeNull();
    expect(await getCues(tdb.db, scope, a.id)).toBeNull();
    expect(await autocue(deps, { ...a.payload, assetId: randomUUID() })).toBeNull();
    const first = await autocue(deps, a.payload);
    const second = await autocue(deps, a.payload);
    expect(second?.updatedAt).toEqual(first?.updatedAt);
  });

  it('backfills assets without cues from the current version', async () => {
    const enqueued: AutocueJobPayload[] = [];
    const jobs = {
      enqueue: async (_job: unknown, payload: AutocueJobPayload) => {
        enqueued.push(payload);
        return {} as never;
      },
      close: async () => {},
    } as unknown as JobPublisher;
    const scope = await tenant();
    const a = await asset(scope, 'song');
    const b = await asset(scope, 'hidden');
    await autocue(deps, b.payload);
    expect(
      (await listAssetsNeedingAutocue(tdb.db, scope, 'autocue/1')).map((x) => x.assetId),
    ).toEqual([a.id]);
    await backfillAutocue({ db: tdb.db, jobs });
    expect(enqueued.filter((p) => p.stationId === scope.stationId)).toEqual([a.payload]);
    // New thresholds: both again, under the new version.
    await setEngineSettings(scope, { autocue: { silenceLu: -50 } });
    enqueued.length = 0;
    await backfillAutocue({ db: tdb.db, jobs });
    const mine = enqueued.filter((p) => p.stationId === scope.stationId);
    expect(mine.map((p) => p.assetId).sort()).toEqual([a.id, b.id].sort());
    expect(mine[0]?.analyzerVersion).toMatch(/^autocue\/1\+/);
  });

  it('enqueues the job from asset.ingested through the durable consumer', async () => {
    const queue = await connectQueue(rabbitUrl, { prefix: `test-${randomUUID().slice(0, 8)}` });
    const events = createEventPublisher(queue.rabbit, queue.topology, realtimeEventSchema);
    const keys: string[] = [];
    const jobs = {
      enqueue: async (_job: unknown, payload: AutocueJobPayload) => {
        keys.push(autocueIdempotencyKey(payload));
        return {} as never;
      },
      close: async () => {},
    } as unknown as JobPublisher;
    const [running] = startJobTriggers(queue, [createAutocueTrigger(async () => tdb.db)], jobs);
    try {
      await running?.ready;
      const scope = await tenant();
      const a = await asset(scope, 'song');
      const files = await listAssetFiles(tdb.db, scope, a.id);
      const ref = (role: 'master' | 'playout') => {
        const f = files.find((x) => x.role === role);
        if (!f) throw new Error(role);
        return {
          fileId: f.id,
          storageKey: f.storageKey,
          sha256: f.sha256,
          sizeBytes: f.sizeBytes,
          codec: f.codec,
          sampleRate: f.sampleRate,
          channels: f.channels,
          durationSamples: f.durationSamples,
          flacBlockSize: f.flacBlockSize,
        };
      };
      const event: RealtimeEvent = {
        id: randomUUID(),
        stationId: scope.stationId,
        at: new Date().toISOString(),
        type: 'asset.ingested',
        data: {
          orgId: scope.orgId,
          assetId: a.id,
          uploadId: randomUUID(),
          master: ref('master'),
          playout: ref('playout'),
        },
      };
      await events.publish(event);
      const key = `autocue:${a.id}:${a.sha256}:autocue/1`;
      const deadline = Date.now() + 10_000;
      while (!keys.includes(key)) {
        if (Date.now() > deadline) throw new Error(`no job enqueued; got ${keys.join(', ')}`);
        await new Promise((r) => setTimeout(r, 50));
      }
    } finally {
      await running?.close();
      await events.close();
      await deleteEventQueue(queue.rabbit, queue.topology, AUTOCUE_EVENT_QUEUE);
      await deleteTopology(queue.rabbit, queue.topology);
      await queue.close();
    }
  });
});
