// Ingest against the dev Postgres and Garage, with audio generated by ffmpeg. Needs ffmpeg on
// the PATH and the S3_* variables (skipped without S3_ENDPOINT, like @ondes/storage's tests).

const exec = promisify(execFile);
const enabled = Boolean(process.env.S3_ENDPOINT);
const system: Actor = { type: 'system', name: 'test' };
const user: Actor = { type: 'user', userId: '0199f6a0-0000-7000-8000-00000000000a' };
const tools = defaultTools();

let tdb: TestDatabase;
let storage: Storage;
let dir: string;
const events: RealtimeEvent[] = [];
let deps: IngestDeps;
const fixtures: Record<string, string> = {};

async function ffmpeg(...args: string[]) {
  await exec(tools.ffmpeg, ['-nostdin', '-v', 'error', '-y', ...args]);
}

beforeAll(async () => {
  if (!enabled) return;
  tdb = await createTestDatabase();
  storage = createS3Storage(loadStorageConfig());
  dir = await mkdtemp(join(tmpdir(), 'ondes-ingest-test-'));
  deps = {
    db: tdb.db,
    storage,
    tools,
    publish: async (event) => {
      events.push(event);
    },
  };
  // Random tone so each run hashes differently (keys never collide between runs).
  const tone = () => `sine=frequency=${200 + Math.floor(Math.random() * 2000)}:duration=3`;
  fixtures.wav = join(dir, 'tone.wav');
  await ffmpeg(
    '-f',
    'lavfi',
    '-i',
    `${tone()}:sample_rate=48000`,
    '-ac',
    '2',
    '-c:a',
    'pcm_s24le',
    fixtures.wav,
  );
  fixtures.mp3 = join(dir, 'tone.mp3');
  await ffmpeg(
    '-f',
    'lavfi',
    '-i',
    tone(),
    '-c:a',
    'libmp3lame',
    '-b:a',
    '128k',
    '-id3v2_version',
    '3',
    '-metadata',
    'title=Mistral',
    '-metadata',
    'artist=Ana;Bo',
    '-metadata',
    'album=Vents',
    '-metadata',
    'date=2019',
    '-metadata',
    'genre=Jazz',
    '-metadata',
    'TSRC=FRZ031400123',
    fixtures.mp3,
  );
  // Already lossless and 44.1 kHz, but with 4096-sample blocks: still re-encoded.
  fixtures.flac = join(dir, 'tone.flac');
  await ffmpeg(
    '-f',
    'lavfi',
    '-i',
    `${tone()}:sample_rate=44100`,
    '-c:a',
    'flac',
    '-frame_size',
    '4096',
    fixtures.flac,
  );
  fixtures.corrupt = join(dir, 'corrupt.mp3');
  await writeFile(fixtures.corrupt, randomBytes(64 * 1024));
}, 60_000);

afterAll(async () => {
  await tdb?.drop();
  if (dir) await rm(dir, { recursive: true, force: true });
});

let n = 0;
async function tenant(orgId?: string) {
  n++;
  const org =
    orgId ?? (await createOrganization(tdb.db, system, { slug: `ing-${n}`, name: 'Org' })).id;
  const orgScope = await resolveOrgScope(tdb.db, org);
  const st = await createStation(
    tdb.db,
    { actor: system, scope: orgScope },
    { slug: `ing-fm-${n}`, name: 'FM', timezone: 'Europe/Paris' },
  );
  return resolveStationScope(tdb.db, org, st.id);
}

/** What the upload API leaves behind: a staged object and a `queued` upload row. */
async function stage(scope: StationScope, file: string, filename: string) {
  const bytes = await readFile(file);
  const stagingKey = `${orgPrefix(scope.orgId)}uploads/${randomUUID()}`;
  await storage.put(stagingKey, bytes);
  const ctx = { actor: user, scope };
  const row = await createUpload(tdb.db, ctx, {
    filename,
    sizeBytes: bytes.length,
    contentType: null,
    assetType: 'song',
    stagingKey,
    s3UploadId: 'test',
    partSize: bytes.length,
    partCount: 1,
  });
  await transitionUpload(tdb.db, ctx, row.id, ['uploading'], {
    status: 'queued',
    s3UploadId: null,
  });
  return { id: row.id, stagingKey };
}

const run = { attempt: 1, isLastAttempt: false };
const payload = (scope: StationScope, uploadId: string) => ({
  uploadId,
  orgId: scope.orgId,
  stationId: scope.stationId,
});

async function download(key: string, to: string) {
  const { body } = await storage.get(key);
  await pipeline(body, createWriteStream(to));
}

/** Sample counts of every audio frame, as ffprobe decodes them. */
async function frameSizes(path: string): Promise<number[]> {
  const { stdout } = await exec(tools.ffprobe, [
    '-v',
    'error',
    '-select_streams',
    'a:0',
    '-show_entries',
    'frame=nb_samples',
    '-of',
    'csv=p=0',
    path,
  ]);
  return stdout.trim().split('\n').map(Number);
}

describe.skipIf(!enabled)('ingest (integration)', () => {
  it.each([
    ['wav', 'tone.wav', 'pcm_s24le', 24],
    ['mp3', 'tone.mp3', 'mp3', 16],
    ['flac', 'tone.flac', 'flac', 16],
  ] as const)(
    'ingests a %s: master as uploaded, FLAC playout on a 1024-sample grid',
    async (kind, filename, codec, playoutBits) => {
      const scope = await tenant();
      const up = await stage(scope, fixtures[kind] as string, filename);
      await ingest(deps, payload(scope, up.id), run);

      const upload = await getUpload(tdb.db, scope, up.id);
      expect(upload).toMatchObject({ status: 'ingested', errorCode: null });
      const asset = await getAssetDetail(tdb.db, scope, upload.assetId as string);
      const master = asset.files.find((f) => f.role === 'master');
      const playout = asset.files.find((f) => f.role === 'playout');
      expect(master).toMatchObject({ codec, sha256: upload.sha256 });
      expect(playout).toMatchObject({
        codec: 'flac',
        sampleRate: 44_100,
        flacBlockSize: 1024,
        bitDepth: playoutBits,
        durationSamples: 132_300,
      });
      expect(asset.durationMs).toBe(3000);

      // The stored playout object, checked independently: STREAMINFO and ffprobe's frames.
      const local = join(dir, `${up.id}.flac`);
      await download(playout?.storageKey as string, local);
      expect(await readFlacStreamInfo(local)).toMatchObject({
        minBlockSize: 1024,
        maxBlockSize: 1024,
        sampleRate: 44_100,
      });
      const frames = await frameSizes(local);
      expect(frames.slice(0, -1).every((size) => size === 1024)).toBe(true);
      expect(frames.reduce((a, b) => a + b, 0)).toBe(132_300);
      // The master is the uploaded file, byte for byte.
      const { body } = await storage.get(master?.storageKey as string);
      const chunks: Buffer[] = [];
      for await (const chunk of body) chunks.push(chunk as Buffer);
      expect(Buffer.concat(chunks).equals(await readFile(fixtures[kind] as string))).toBe(true);

      // Staging object gone; asset.ingested out with the playout copy.
      expect(await storage.head(up.stagingKey)).toBeNull();
      const event = events.find((e) => e.type === 'asset.ingested' && e.data.uploadId === up.id);
      expect(event).toMatchObject({
        stationId: scope.stationId,
        data: {
          assetId: asset.id,
          playout: { storageKey: playout?.storageKey, flacBlockSize: 1024 },
        },
      });
    },
  );

  it('reads ID3 tags into the asset', async () => {
    const scope = await tenant();
    const up = await stage(scope, fixtures.mp3 as string, 'tone.mp3');
    await ingest(deps, payload(scope, up.id), run);
    const { assetId } = await getUpload(tdb.db, scope, up.id);
    const asset = await getAssetDetail(tdb.db, scope, assetId as string);
    expect(asset).toMatchObject({
      title: 'Mistral',
      artists: ['Ana', 'Bo'],
      album: 'Vents',
      year: 2019,
      isrc: 'FRZ031400123',
      sourceFilename: 'tone.mp3',
    });
    expect(asset.tags.map((t) => [t.key, t.value])).toEqual([['genre', 'Jazz']]);
  });

  it('reports a duplicate in the station instead of creating a second asset', async () => {
    const scope = await tenant();
    const first = await stage(scope, fixtures.wav as string, 'a.wav');
    await ingest(deps, payload(scope, first.id), run);
    const original = await getUpload(tdb.db, scope, first.id);

    const second = await stage(scope, fixtures.wav as string, 'a (copy).wav');
    await ingest(deps, payload(scope, second.id), run);
    const dup = await getUpload(tdb.db, scope, second.id);
    expect(dup).toMatchObject({
      status: 'duplicate',
      duplicateOfAssetId: original.assetId,
      assetId: null,
      sha256: original.sha256,
    });
    expect(dup.error).toContain(original.assetId);
    expect((await listAssets(tdb.db, scope)).items).toHaveLength(1);
    expect(
      events.some(
        (e) =>
          e.type === 'upload.updated' && e.data.id === second.id && e.data.status === 'duplicate',
      ),
    ).toBe(true);
    expect(await storage.head(second.stagingKey)).toBeNull();
  });

  it('shares stored objects across stations of an org, charged once', async () => {
    const a = await tenant();
    const b = await tenant(a.orgId);
    const upA = await stage(a, fixtures.flac as string, 'x.flac');
    const upB = await stage(b, fixtures.flac as string, 'x.flac');
    await ingest(deps, payload(a, upA.id), run);
    await ingest(deps, payload(b, upB.id), run);
    expect((await getUpload(tdb.db, b, upB.id)).status).toBe('ingested');
    const refs = (await tdb.db.select().from(storageObject)).filter((r) => r.orgId === a.orgId);
    expect(refs).toHaveLength(2);
    expect(refs.every((r) => r.refCount === 2)).toBe(true);
  });

  it('uploads an object again when it was swept just before the charge', async () => {
    const scope = await tenant();
    const first = await stage(scope, fixtures.mp3 as string, 'a.mp3');
    await ingest(deps, payload(scope, first.id), run);
    const { assetId } = await getUpload(tdb.db, scope, first.id);
    const before = await getAssetDetail(tdb.db, scope, assetId as string);
    // Delete the asset and let the sweeper remove its objects from the bucket.
    await deleteAsset(tdb.db, { actor: user, scope }, assetId as string);
    await sweepStorageDeletions(tdb.db, storage, { graceMs: 0 });
    for (const file of before.files) expect(await storage.head(file.storageKey)).toBeNull();

    const again = await stage(scope, fixtures.mp3 as string, 'a.mp3');
    await ingest(deps, payload(scope, again.id), run);
    const upload = await getUpload(tdb.db, scope, again.id);
    expect(upload.status).toBe('ingested');
    const after = await getAssetDetail(tdb.db, scope, upload.assetId as string);
    for (const file of after.files) {
      expect((await storage.head(file.storageKey))?.size).toBe(file.sizeBytes);
    }
  });

  it('quarantines a corrupt file with the ffprobe error, without retrying', async () => {
    const scope = await tenant();
    const up = await stage(scope, fixtures.corrupt as string, 'corrupt.mp3');
    await ingest(deps, payload(scope, up.id), run);
    const upload = await getUpload(tdb.db, scope, up.id);
    expect(upload).toMatchObject({
      status: 'quarantined',
      errorCode: 'probe_failed',
      assetId: null,
    });
    expect(upload.error).toBeTruthy();
    // Kept for inspection.
    expect(await storage.head(up.stagingKey)).not.toBeNull();
    expect((await listAssets(tdb.db, scope)).items).toHaveLength(0);
  });

  it('is idempotent: running it again changes nothing and re-sends the event', async () => {
    const scope = await tenant();
    const up = await stage(scope, fixtures.wav as string, 'b.wav');
    await ingest(deps, payload(scope, up.id), run);
    const done = await getUpload(tdb.db, scope, up.id);
    const count = events.filter(
      (e) => e.type === 'asset.ingested' && e.data.uploadId === up.id,
    ).length;

    await ingest(deps, payload(scope, up.id), { attempt: 2, isLastAttempt: false });
    expect(await getUpload(tdb.db, scope, up.id)).toMatchObject({
      status: 'ingested',
      assetId: done.assetId,
    });
    expect((await listAssets(tdb.db, scope)).items).toHaveLength(1);
    expect(
      events.filter((e) => e.type === 'asset.ingested' && e.data.uploadId === up.id).length,
    ).toBe(count + 1);
  });

  it('resumes an attempt that died after creating the asset', async () => {
    const scope = await tenant();
    const up = await stage(scope, fixtures.flac as string, 'c.flac');
    let calls = 0;
    // Fail the first bucket write after the asset and its files exist.
    const flaky: Storage = {
      ...storage,
      put: async (...args) => {
        calls++;
        if (calls === 1) throw new Error('S3 unavailable');
        return storage.put(...args);
      },
    };
    await expect(ingest({ ...deps, storage: flaky }, payload(scope, up.id), run)).rejects.toThrow(
      'S3 unavailable',
    );
    const mid = await getUpload(tdb.db, scope, up.id);
    expect(mid).toMatchObject({ status: 'processing' });
    expect(mid.assetId).not.toBeNull();

    await ingest({ ...deps, storage: flaky }, payload(scope, up.id), {
      attempt: 2,
      isLastAttempt: false,
    });
    expect(await getUpload(tdb.db, scope, up.id)).toMatchObject({
      status: 'ingested',
      assetId: mid.assetId,
    });
    expect((await listAssets(tdb.db, scope)).items).toHaveLength(1);
  });

  it('marks the upload failed when the last attempt fails', async () => {
    const scope = await tenant();
    const up = await stage(scope, fixtures.wav as string, 'd.wav');
    const broken: Storage = {
      ...storage,
      get: async () => {
        throw new Error('S3 unavailable');
      },
    };
    await expect(
      ingest({ ...deps, storage: broken }, payload(scope, up.id), {
        attempt: 4,
        isLastAttempt: true,
      }),
    ).rejects.toThrow();
    expect(await getUpload(tdb.db, scope, up.id)).toMatchObject({
      status: 'failed',
      errorCode: 'internal',
    });
  });
});
