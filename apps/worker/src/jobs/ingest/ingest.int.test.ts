    const { uploadId } = await storage.createMultipartUpload(stagingKey);
    const open = await createUpload(tdb.db, ctx, {
      filename: 'left.wav',
      sizeBytes: 10,
      contentType: null,
      assetType: 'song',
      stagingKey,
      s3UploadId: uploadId,
      partSize: 10,
      partCount: 1,
    });
    const lost = await stage(scope, fixtures.wav as string, 'lost.wav');
    const old = new Date(Date.now() - 2 * 24 * 60 * 60 * 1000).toISOString();
    await patchUpload(open.id, { updated_at: old });
    await patchUpload(lost.id, { updated_at: old });

    const enqueued: IngestJobPayload[] = [];
    const jobs = {
      enqueue: async (_job: unknown, p: unknown) => {
        enqueued.push(p as IngestJobPayload);
        return {} as never;
      },
      close: async () => {},
    };
    const result = await sweepUploads({ db: tdb.db, storage, jobs });
    expect(result.expired).toContain(open.id);
    expect(result.requeued).toContain(lost.id);
    expect(await getUpload(tdb.db, scope, open.id)).toMatchObject({
      status: 'aborted',
      errorCode: 'expired',
    });
    await expect(storage.listParts(stagingKey, uploadId)).rejects.toThrow();
    expect(enqueued).toContainEqual(payload(scope, lost.id));
    // Touched: the next sweep leaves it alone.
