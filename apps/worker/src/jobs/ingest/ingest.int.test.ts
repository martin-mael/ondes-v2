let n = 0;
async function tenant(orgId?: string) {
  n++;
  const org =
    orgId ?? (await createOrganization(tdb.db, system, { slug: `ing-${n}`, name: 'Org' })).id;
  const orgScope = await resolveOrgScope(tdb.db, org);
  const st = await createStation(
    tdb.db,
    { actor: system, scope: orgScope },
    { slug: `ing-fm-${n}`, name: 'FM', timezone: 'Europe/Paris' },
  );
  return resolveStationScope(tdb.db, org, st.id);
}

/** What the upload API leaves behind: a staged object and a `queued` upload row. */
async function stage(scope: StationScope, file: string, filename: string) {
  const bytes = await readFile(file);
  const stagingKey = `${orgPrefix(scope.orgId)}uploads/${randomUUID()}`;
  await storage.put(stagingKey, bytes);
  const ctx = { actor: user, scope };
  const row = await createUpload(tdb.db, ctx, {
    filename,
    sizeBytes: bytes.length,
    contentType: null,
    assetType: 'song',
    stagingKey,
    s3UploadId: 'test',
    partSize: bytes.length,
    partCount: 1,
  });
  await transitionUpload(tdb.db, ctx, row.id, ['uploading'], {
    status: 'queued',
    s3UploadId: null,
  });
  return { id: row.id, stagingKey };
}

const run = { attempt: 1, isLastAttempt: false };
/** Raw update of an upload row, to set up states (snake_case columns). */
async function patchUpload(id: string, set: Record<string, string | null>) {
  await tdb.sql`update upload set ${tdb.sql(set)} where id = ${id}`;
}
const payload = (scope: StationScope, uploadId: string) => ({
  uploadId,
  orgId: scope.orgId,
  stationId: scope.stationId,
  generation: 0,
});

async function download(key: string, to: string) {
  const { body } = await storage.get(key);
  await pipeline(body, createWriteStream(to));
}

/** Sample counts of every audio frame, as ffprobe decodes them. */
async function frameSizes(path: string): Promise<number[]> {
  const { stdout } = await exec(tools.ffprobe, [
    '-v',
    'error',
    '-select_streams',
    'a:0',
    '-show_entries',
    'frame=nb_samples',
    '-of',
    'csv=p=0',
    path,
  ]);
  return stdout.trim().split('\n').map(Number);
}

