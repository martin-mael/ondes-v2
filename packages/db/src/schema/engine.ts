import { sql } from 'drizzle-orm';
import {
  check,
  foreignKey,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';
import { station } from './tenancy.ts';

// Station engine lifecycle (#35): one Liquidsoap container per station, managed by the api
// through the Docker socket proxy (apps/api/src/modules/engine/lifecycle).

const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();
const updatedAt = () =>
  timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());

export const ENGINE_DESIRED_STATES = ['running', 'stopped'] as const;
export type EngineDesiredState = (typeof ENGINE_DESIRED_STATES)[number];

/**
 * A station's engine: what the api should keep running, and its secrets. Secrets are
 * generated by the lifecycle and stored encrypted (AES-256-GCM, key derived from
 * AUTH_SECRET); they reach the container through its environment, never the script.
 */
export const stationEngine = pgTable(
  'station_engine',
  {
    stationId: uuid('station_id').primaryKey(),
    orgId: uuid('org_id').notNull(),
    /**
     * `stopped` until someone starts the engine: the row also exists for stations whose
     * secrets were only read (e.g. by the Icecast config sync, #32).
     */
    desiredState: text('desired_state', { enum: ENGINE_DESIRED_STATES })
      .notNull()
      .default('stopped'),
    /** Bearer token of the control API and of the engine's event posts. Encrypted. */
    controlTokenEnc: text('control_token_enc').notNull(),
    /** Shared live password (when no live auth webhook is set). Encrypted. */
    livePasswordEnc: text('live_password_enc').notNull(),
    /** Icecast source password generated for this station. Encrypted. */
    icecastSourcePasswordEnc: text('icecast_source_password_enc').notNull(),
    /** `config_version` of the script the current container was created with. */
    configVersion: text('config_version'),
    /** Docker id of the current container, if one was created. */
    containerId: text('container_id'),
    /**
     * When the restart-storm guard stopped this engine; it stays down until a person
     * restarts it. Shared by every api replica, and survives api restarts.
     */
    stormAt: timestamp('storm_at', { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    foreignKey({
      name: 'station_engine_station_fk',
      columns: [t.stationId, t.orgId],
      foreignColumns: [station.id, station.orgId],
      // Restrict, not cascade: the engine's container must be removed first
      // (`engineLifecycle.remove`), or deleting the station would leave it streaming.
    }).onDelete('restrict'),
    index('station_engine_desired_state_idx').on(t.desiredState),
  ],
);

export const ENGINE_PORT_PURPOSES = ['live'] as const;
export type EnginePortPurpose = (typeof ENGINE_PORT_PURPOSES)[number];

/**
 * Host ports published by station engines, allocated from a pool (the range is
 * configuration, not data: `ENGINE_LIVE_PORT_MIN`..`MAX`). The primary key makes a port
 * belong to one station at most; the unique constraint gives a station one port per purpose.
 * Only harbor live inputs are published; the control and metrics ports never are.
 */
export const enginePort = pgTable(
  'engine_port',
  {
    port: integer('port').primaryKey(),
    stationId: uuid('station_id')
      .notNull()
      // Restrict: a port is freed by `engineLifecycle.remove`, once its container is gone.
      .references(() => station.id, { onDelete: 'restrict' }),
    purpose: text('purpose', { enum: ENGINE_PORT_PURPOSES }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    unique('engine_port_station_purpose_key').on(t.stationId, t.purpose),
    check('engine_port_range', sql`${t.port} between 1024 and 65535`),
  ],
);
